def psnr_from_mse(mse):
    if not math.isfinite(mse):
        return float("nan")

    if mse <= 1e-12:
        return 99.0

    return (
        10.0
        * math.log10(
            1.0 / mse
        )
    )


def expand_mask(
        mask,
        tensor
):
    mask = (
        mask
        .detach()
        .bool()
    )

    if mask.dim() == 3:
        mask = mask.unsqueeze(
            1
        )

    if (
            mask.shape[1] == 1
            and
            tensor.shape[1] != 1
    ):
        mask = mask.expand(
            -1,
            tensor.shape[1],
            -1,
            -1
        )

    return mask


def masked_mse(
        prediction,
        target,
        mask
):
    prediction = (
        prediction
        .detach()
        .float()
        .clamp(
            0.0,
            1.0
        )
    )

    target = (
        target
        .detach()
        .float()
        .clamp(
            0.0,
            1.0
        )
    )

    mask = expand_mask(
        mask,
        prediction
    )

    if not mask.any():
        return float("nan")

    difference = (
        prediction
        - target
    )[
        mask
    ]

    return float(
        (
            difference
            * difference
        )
        .mean()
        .item()
    )


def full_psnr(
        prediction,
        target
):
    prediction = (
        prediction
        .detach()
        .float()
        .clamp(
            0.0,
            1.0
        )
    )

    target = (
        target
        .detach()
        .float()
        .clamp(
            0.0,
            1.0
        )
    )

    mse = float(
        (
            prediction
            - target
        )
        .pow(2)
        .mean()
        .item()
    )

    return psnr_from_mse(
        mse
    )


