def parse_args():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--checkpoint",
        type=str,
        required=True
    )

    parser.add_argument(
        "--dataset_root",
        type=str,
        default="./datasets/stage2_1280x720"
    )

    parser.add_argument(
        "--eval_threshold",
        type=float,
        default=0.50
    )

    parser.add_argument(
        "--min_region_pixels",
        type=int,
        default=100
    )

    parser.add_argument(
        "--num_workers",
        type=int,
        default=0
    )

    return parser.parse_args()


# ============================================================
# Main
# ============================================================

@torch.no_grad()
def main():

    args = parse_args()

    device = torch.device(
        "cuda"
        if torch.cuda.is_available()
        else "cpu"
    )

    # ========================================================
    # Checkpoint
    # ========================================================

    checkpoint_path = Path(
        args.checkpoint
    )

    checkpoint = torch.load(
        checkpoint_path,
        map_location=device
    )

    checkpoint_args = checkpoint.get(
        "args",
        {}
    )

    channels = checkpoint_args.get(
        "channels",
        64
    )

    blocks = checkpoint_args.get(
        "blocks",
        8
    )

    lr_patch = checkpoint_args.get(
        "lr_patch",
        192
    )

    val_ratio = checkpoint_args.get(
        "val_ratio",
        0.10
    )

    seed = checkpoint_args.get(
        "seed",
        1234
    )

    split_mode = checkpoint_args.get(
        "split_mode",
        "frame"
    )

    region_boost = checkpoint_args.get(
        "region_boost",
        1.0
    )

    region_threshold = checkpoint_args.get(
        "region_threshold",
        0.01
    )

    region_range = checkpoint_args.get(
        "region_range",
        0.10
    )

    region_smooth = checkpoint_args.get(
        "region_smooth",
        5
    )

    print(
        f"Device: {device}"
    )

    print(
        f"Checkpoint: {checkpoint_path}"
    )

    print(
        f"Checkpoint epoch: "
        f"{checkpoint.get('epoch', 'unknown')}"
    )

    print(
        f"Split mode: {split_mode}"
    )

    print(
        f"Eval threshold: "
        f"{args.eval_threshold}"
    )

    # ========================================================
    # Dataset
    # ========================================================

    records = load_manifest(
        args.dataset_root
    )

    if split_mode == "sequence":

        (
            train_records,
            val_records
        ) = split_records_by_sequence(
            records,
            val_ratio=val_ratio,
            seed=seed
        )

    else:

        (
            train_records,
            val_records
        ) = split_records(
            records,
            val_ratio=val_ratio,
            seed=seed
        )

    print(
        f"Total pairs : "
        f"{len(records)}"
    )

    print(
        f"Train pairs : "
        f"{len(train_records)}"
    )

    print(
        f"Val pairs   : "
        f"{len(val_records)}"
    )

    val_dataset = Stage2SRDataset(
        dataset_root=args.dataset_root,
        records=val_records,
        train=False,
        lr_patch_size=lr_patch,
        horizontal_flip=False
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=1,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=(
            device.type == "cuda"
        )
    )

    # ========================================================
    # Model
    # ========================================================

    model = ResidualSRNet(
        channels=channels,
        num_blocks=blocks,
        block_res_scale=0.10,
        output_res_scale=0.20,
        scale_num=5,
        scale_den=3
    ).to(
        device
    )

    model.load_state_dict(
        checkpoint[
            "model"
        ],
        strict=True
    )

    model.eval()

    # ========================================================
    # Evaluation
    # ========================================================

    rows = []

    for batch_index, batch in enumerate(
            val_loader,
            start=1
    ):

        stem = (
            batch[
                "stem"
            ][0]
        )

        sequence_id = (
            get_sequence_id_from_stem(
                stem
            )
        )

        lr = (
            batch[
                "lr"
            ]
            .to(
                device,
                non_blocking=True
            )
        )

        hr = (
            batch[
                "hr"
            ]
            .to(
                device,
                non_blocking=True
            )
        )

        sr = (
            model(
                lr
            )
            .clamp(
                0.0,
                1.0
            )
        )

        bicubic = (
            model.upscale_bicubic(
                lr
            )
            .clamp(
                0.0,
                1.0
            )
        )

        # ====================================================
        # Same Region definition used by current evaluation
        # ====================================================

        (
            _,
            score_map
        ) = build_region_weight(
            bicubic=bicubic,
            target=hr,
            threshold=region_threshold,
            change_range=region_range,
            region_boost=region_boost,
            smooth_kernel=region_smooth
        )

        region_mask = (
            score_map
            >= args.eval_threshold
        )

        region_pixel_count = int(
            region_mask
            .sum()
            .item()
        )

        region_coverage_percent = (
            100.0
            * region_pixel_count
            / max(
                region_mask.numel(),
                1
            )
        )

        # ====================================================
        # Region PSNR
        # ====================================================

        bicubic_region_psnr = (
            psnr_from_mse(
                masked_mse(
                    bicubic,
                    hr,
                    region_mask
                )
            )
        )

        sr_region_psnr = (
            psnr_from_mse(
                masked_mse(
                    sr,
                    hr,
                    region_mask
                )
            )
        )

        # ====================================================
        # Correction capacity
        # ====================================================

        correction = (
            calculate_correction_statistics(
                bicubic=bicubic,
                sr=sr,
                target=hr,
                region_mask=region_mask
            )
        )

        bicubic_full_psnr = (
            full_psnr(
                bicubic,
                hr
            )
        )

        sr_full_psnr = (
            full_psnr(
                sr,
                hr
            )
        )

        row = {
            "stem":
                stem,

            "sequence_id":
                sequence_id,

            "region_pixel_count":
                region_pixel_count,

            "region_coverage_percent":
                region_coverage_percent,

            "bicubic_full_psnr":
                bicubic_full_psnr,

            "sr_full_psnr":
                sr_full_psnr,

            "full_gain":
                sr_full_psnr
                - bicubic_full_psnr,

            "bicubic_region_psnr":
                bicubic_region_psnr,

            "sr_region_psnr":
                sr_region_psnr,

            "region_gain":
                sr_region_psnr
                - bicubic_region_psnr,

            **correction,
        }

        rows.append(
            row
        )

        if (
                batch_index % 50 == 0
                or
                batch_index == len(
                    val_loader
                )
        ):
            print(
                f"Evaluate "
                f"{batch_index:04d}/"
                f"{len(val_loader):04d}"
            )

    # ========================================================
    # Valid rows
    # ========================================================

    valid_rows = [
        row
        for row in rows
        if (
            row[
                "region_pixel_count"
            ]
            >= args.min_region_pixels
            and
            math.isfinite(
                row[
                    "bicubic_region_psnr"
                ]
            )
            and
            math.isfinite(
                row[
                    "region_gain"
                ]
            )
        )
    ]

    # ========================================================
    # CSV
    # ========================================================

    threshold_text = (
        f"{args.eval_threshold:.3f}"
        .replace(
            ".",
            "p"
        )
    )

    csv_path = (
        checkpoint_path.parent
        / (
            f"{checkpoint_path.stem}"
            f"_stage1_stage2_capacity_"
            f"{threshold_text}.csv"
        )
    )

    fieldnames = [
        "stem",
        "sequence_id",
        "region_pixel_count",
        "region_coverage_percent",

        "bicubic_full_psnr",
        "sr_full_psnr",
        "full_gain",

        "bicubic_region_psnr",
        "sr_region_psnr",
        "region_gain",

        "required_correction_mae",
        "actual_residual_mae",
        "remaining_error_mae",

        "correction_ratio",
        "error_reduction_fraction",

        "residual_alignment_cosine",
        "residual_projection_fraction",
    ]

    with open(
            csv_path,
            "w",
            newline="",
            encoding="utf-8-sig"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames
        )

        writer.writeheader()

        writer.writerows(
            rows
        )

    # ========================================================
    # Overall
    # ========================================================

    print()
    print(
        "========================================"
    )
    print(
        "Stage1 -> Stage2 capacity analysis"
    )
    print(
        "========================================"
    )

    print(
        f"All images   : "
        f"{len(rows)}"
    )

    print(
        f"Valid images : "
        f"{len(valid_rows)}"
    )

    print_group(
        "Overall",
        valid_rows
    )

    # ========================================================
    # Sequence
    # ========================================================

    print_sequence_summary(
        valid_rows
    )

    # ========================================================
    # Stage1 difficulty quartiles
    # ========================================================

    print_difficulty_quartiles(
        valid_rows
    )

    # ========================================================
    # Hardest images
    # ========================================================

    print()
    print(
        "========================================"
    )
    print(
        "Hardest 10 images"
    )
    print(
        "========================================"
    )

    hardest_rows = sorted(
        valid_rows,
        key=lambda row:
        row[
            "bicubic_region_psnr"
        ]
    )[
        :10
    ]

    for row in hardest_rows:

        print(
            f"{row['stem']} | "
            f"Bicubic "
            f"{row['bicubic_region_psnr']:.4f} dB | "
            f"Gain "
            f"{row['region_gain']:+.4f} dB | "
            f"ReqMAE "
            f"{row['required_correction_mae']:.6f} | "
            f"ResidualMAE "
            f"{row['actual_residual_mae']:.6f} | "
            f"Ratio "
            f"{row['correction_ratio']:.4f} | "
            f"Align "
            f"{row['residual_alignment_cosine']:+.4f} | "
            f"Proj "
            f"{row['residual_projection_fraction']:+.4f}"
        )

    print()
    print(
        f"CSV saved: "
        f"{csv_path}"
    )


if __name__ == "__main__":
    main()