def mean_finite(
        rows,
        key
):
    values = [
        row[
            key
        ]
        for row in rows
        if math.isfinite(
            row[
                key
            ]
        )
    ]

    if not values:
        return float("nan")

    return float(
        np.mean(
            values
        )
    )


def print_group(
        label,
        rows
):
    print()
    print(
        label
    )

    print(
        f"  N                        : "
        f"{len(rows)}"
    )

    print(
        f"  Bicubic Region PSNR      : "
        f"{mean_finite(rows, 'bicubic_region_psnr'):.4f} dB"
    )

    print(
        f"  SR Region PSNR           : "
        f"{mean_finite(rows, 'sr_region_psnr'):.4f} dB"
    )

    print(
        f"  Region Gain              : "
        f"{mean_finite(rows, 'region_gain'):+.4f} dB"
    )

    print(
        f"  Required correction MAE  : "
        f"{mean_finite(rows, 'required_correction_mae'):.6f}"
    )

    print(
        f"  Actual residual MAE      : "
        f"{mean_finite(rows, 'actual_residual_mae'):.6f}"
    )

    print(
        f"  Correction ratio         : "
        f"{mean_finite(rows, 'correction_ratio'):.4f}"
    )

    print(
        f"  Error reduction fraction : "
        f"{mean_finite(rows, 'error_reduction_fraction'):+.4f}"
    )

    print(
        f"  Alignment cosine         : "
        f"{mean_finite(rows, 'residual_alignment_cosine'):+.4f}"
    )

    print(
        f"  Projection fraction      : "
        f"{mean_finite(rows, 'residual_projection_fraction'):+.4f}"
    )


def print_sequence_summary(
        rows
):
    print()
    print(
        "========================================"
    )
    print(
        "Sequence summary"
    )
    print(
        "========================================"
    )

    sequence_ids = sorted(
        {
            row[
                "sequence_id"
            ]
            for row in rows
        }
    )

    for sequence_id in sequence_ids:

        sequence_rows = [
            row
            for row in rows
            if (
                row[
                    "sequence_id"
                ]
                == sequence_id
            )
        ]

        print_group(
            f"Sequence {sequence_id}",
            sequence_rows
        )


def print_difficulty_quartiles(
        rows
):
    ordered = sorted(
        rows,
        key=lambda row:
        row[
            "bicubic_region_psnr"
        ]
    )

    groups = np.array_split(
        np.array(
            ordered,
            dtype=object
        ),
        4
    )

    print()
    print(
        "========================================"
    )
    print(
        "Stage1 difficulty quartiles"
    )
    print(
        "Q1 = hardest / lowest Bicubic Region PSNR"
    )
    print(
        "Q4 = easiest / highest Bicubic Region PSNR"
    )
    print(
        "========================================"
    )

    for group_index, group in enumerate(
            groups,
            start=1
    ):

        group_rows = list(
            group
        )

        values = np.array(
            [
                row[
                    "bicubic_region_psnr"
                ]
                for row in group_rows
            ],
            dtype=np.float64
        )

        print()
        print(
            f"Q{group_index} | "
            f"Bicubic Region PSNR "
            f"{values.min():.4f} - "
            f"{values.max():.4f} dB"
        )

        print_group(
            "  Summary",
            group_rows
        )


