# Stage1 -> Stage2 correction statistics
# ============================================================

def calculate_correction_statistics(
        bicubic,
        sr,
        target,
        region_mask
):
    bicubic = (
        bicubic
        .detach()
        .float()
        .clamp(
            0.0,
            1.0
        )
    )

    sr = (
        sr
        .detach()
        .float()
        .clamp(
            0.0,
            1.0
        )
    )

    target = (
        target
        .detach()
        .float()
        .clamp(
            0.0,
            1.0
        )
    )

    mask = expand_mask(
        region_mask,
        bicubic
    )

    if not mask.any():

        return {
            "required_correction_mae":
                float("nan"),

            "actual_residual_mae":
                float("nan"),

            "remaining_error_mae":
                float("nan"),

            "correction_ratio":
                float("nan"),

            "error_reduction_fraction":
                float("nan"),

            "residual_alignment_cosine":
                float("nan"),

            "residual_projection_fraction":
                float("nan"),
        }

    # --------------------------------------------------------
    # Ideally necessary correction:
    #
    # Target - Bicubic
    # --------------------------------------------------------

    required = (
        target
        - bicubic
    )[
        mask
    ]

    # --------------------------------------------------------
    # Correction actually generated by Stage2:
    #
    # SR - Bicubic
    # --------------------------------------------------------

    actual = (
        sr
        - bicubic
    )[
        mask
    ]

    # --------------------------------------------------------
    # Error still remaining after Stage2
    # --------------------------------------------------------

    remaining = (
        target
        - sr
    )[
        mask
    ]

    required_mae = float(
        required
        .abs()
        .mean()
        .item()
    )

    actual_mae = float(
        actual
        .abs()
        .mean()
        .item()
    )

    remaining_mae = float(
        remaining
        .abs()
        .mean()
        .item()
    )

    # --------------------------------------------------------
    # How large Stage2 correction is compared with
    # the correction theoretically required
    # --------------------------------------------------------

    correction_ratio = (
        actual_mae
        /
        max(
            required_mae,
            1e-12
        )
    )

    # --------------------------------------------------------
    # MAE reduction achieved by Stage2
    #
    #  1.0 : perfect
    #  0.0 : no improvement
    # <0.0 : worse than Bicubic
    # --------------------------------------------------------

    error_reduction_fraction = (
        1.0
        -
        remaining_mae
        /
        max(
            required_mae,
            1e-12
        )
    )

    # --------------------------------------------------------
    # Direction similarity between actual correction
    # and ideal correction
    #
    # +1 : same direction
    #  0 : unrelated
    # -1 : opposite direction
    # --------------------------------------------------------

    dot = float(
        (
            actual
            * required
        )
        .sum()
        .item()
    )

    actual_norm = float(
        torch.sqrt(
            (
                actual
                * actual
            )
            .sum()
        )
        .item()
    )

    required_norm = float(
        torch.sqrt(
            (
                required
                * required
            )
            .sum()
        )
        .item()
    )

    residual_alignment_cosine = (
        dot
        /
        max(
            actual_norm
            * required_norm,
            1e-12
        )
    )

    # --------------------------------------------------------
    # How much of ideal correction is produced
    # in the correct direction
    #
    # ~1 : ideal correction magnitude
    # ~0 : almost no useful correction
    # <0 : wrong direction
    # --------------------------------------------------------

    required_energy = float(
        (
            required
            * required
        )
        .sum()
        .item()
    )

    residual_projection_fraction = (
        dot
        /
        max(
            required_energy,
            1e-12
        )
    )

    return {
        "required_correction_mae":
            required_mae,

        "actual_residual_mae":
            actual_mae,

        "remaining_error_mae":
            remaining_mae,

        "correction_ratio":
            correction_ratio,

        "error_reduction_fraction":
            error_reduction_fraction,

        "residual_alignment_cosine":
            residual_alignment_cosine,

        "residual_projection_fraction":
            residual_projection_fraction,
    }


